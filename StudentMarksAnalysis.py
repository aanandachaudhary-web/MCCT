marks = [45, 78, 62, 89, 55, 92, 38, 76]
highest = max(marks)
lowest = min(marks)
avg = sum(marks)/ len(marks)

count_avg = 0

for i in marks:
    i > avg
    count_avg += 1

marks.sort()
print (marks)
print("Highest marks:", highest)
print("Lowest Marks:", lowest)
print("Average Marks:", avg)
print(" students scored above the average:",count_avg)
